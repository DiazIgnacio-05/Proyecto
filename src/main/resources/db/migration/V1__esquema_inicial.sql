-- Esquema inicial de Vidriera.
-- Estrategia multi-tenant: base y esquema compartidos; cada tabla que pertenece a un comercio
-- lleva la columna comercio_id. Hibernate la filtra automáticamente (@TenantId) y además las
-- claves foráneas compuestas (id, comercio_id) impiden, a nivel base de datos, relacionar
-- filas de comercios distintos (por ejemplo, un producto de A en una categoría de B).

CREATE TABLE comercio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug              VARCHAR(63)   NOT NULL,
    nombre            VARCHAR(120)  NOT NULL,
    rubro             VARCHAR(20)   NOT NULL,
    estado            VARCHAR(20)   NOT NULL,
    descripcion       VARCHAR(500),
    whatsapp          VARCHAR(20)   NOT NULL,
    telefono          VARCHAR(30),
    email             VARCHAR(120),
    direccion         VARCHAR(200),
    latitud           NUMERIC(9, 6),
    longitud          NUMERIC(9, 6),
    logo_url          VARCHAR(300),
    portada_url       VARCHAR(300),
    color_primario    VARCHAR(7)    NOT NULL,
    color_secundario  VARCHAR(7)    NOT NULL,
    instagram         VARCHAR(100),
    facebook          VARCHAR(100),
    tiktok            VARCHAR(100),
    seo_titulo        VARCHAR(70),
    seo_descripcion   VARCHAR(160),
    dominio_propio    VARCHAR(253),
    cantidad_mesas    INT           NOT NULL DEFAULT 0,
    fecha_alta        DATE          NOT NULL,
    vencimiento_abono DATE,
    notas_internas    VARCHAR(2000),
    creado_en         TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_comercio_slug UNIQUE (slug),
    CONSTRAINT uk_comercio_dominio UNIQUE (dominio_propio),
    CONSTRAINT ck_comercio_slug CHECK (slug ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$'),
    CONSTRAINT ck_comercio_rubro CHECK (rubro IN ('RESTAURANTE', 'ROPA', 'ARTICULOS')),
    CONSTRAINT ck_comercio_estado CHECK (estado IN ('ACTIVO', 'SUSPENDIDO', 'BAJA')),
    CONSTRAINT ck_comercio_colores CHECK (color_primario ~ '^#[0-9a-fA-F]{6}$'
                                      AND color_secundario ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT ck_comercio_mesas CHECK (cantidad_mesas BETWEEN 0 AND 200)
);

-- Módulos adicionales contratados por cada comercio (servicios que se cobran aparte).
CREATE TABLE comercio_modulo (
    comercio_id BIGINT      NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    modulo      VARCHAR(40) NOT NULL,
    PRIMARY KEY (comercio_id, modulo)
);

CREATE TABLE usuario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 VARCHAR(120) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    nombre                VARCHAR(120) NOT NULL,
    rol                   VARCHAR(20)  NOT NULL,
    comercio_id           BIGINT REFERENCES comercio (id) ON DELETE CASCADE,
    activo                BOOLEAN      NOT NULL DEFAULT TRUE,
    debe_cambiar_password BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_en             TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_email_minusculas CHECK (email = lower(email)),
    -- El super-admin no pertenece a ningún comercio; el dueño siempre pertenece a uno.
    CONSTRAINT ck_usuario_rol_comercio CHECK (
        (rol = 'SUPER_ADMIN' AND comercio_id IS NULL) OR (rol = 'DUENO' AND comercio_id IS NOT NULL))
);

CREATE TABLE horario_atencion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT      NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    dia_semana  VARCHAR(9)  NOT NULL,
    apertura    TIME        NOT NULL,
    cierre      TIME        NOT NULL,
    CONSTRAINT ck_horario_dia CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    -- Si cierre < apertura la franja cruza la medianoche (ej. 20:30 a 00:30).
    CONSTRAINT ck_horario_franja CHECK (apertura <> cierre)
);
CREATE INDEX ix_horario_comercio ON horario_atencion (comercio_id);

CREATE TABLE categoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT      NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    nombre      VARCHAR(80) NOT NULL,
    orden       INT         NOT NULL DEFAULT 0,
    activa      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categoria_nombre UNIQUE (comercio_id, nombre),
    CONSTRAINT uk_categoria_id_comercio UNIQUE (id, comercio_id)
);

CREATE TABLE producto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id  BIGINT         NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    categoria_id BIGINT         NOT NULL,
    nombre       VARCHAR(120)   NOT NULL,
    descripcion  VARCHAR(1000),
    precio       NUMERIC(12, 2) NOT NULL,
    disponible   BOOLEAN        NOT NULL DEFAULT TRUE,
    destacado    BOOLEAN        NOT NULL DEFAULT FALSE,
    orden        INT            NOT NULL DEFAULT 0,
    CONSTRAINT uk_producto_id_comercio UNIQUE (id, comercio_id),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id, comercio_id)
        REFERENCES categoria (id, comercio_id) ON DELETE CASCADE,
    CONSTRAINT ck_producto_precio CHECK (precio >= 0)
);
CREATE INDEX ix_producto_comercio_categoria ON producto (comercio_id, categoria_id);

CREATE TABLE imagen_producto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT       NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    producto_id BIGINT       NOT NULL,
    clave       VARCHAR(200) NOT NULL,
    orden       INT          NOT NULL DEFAULT 0,
    CONSTRAINT fk_imagen_producto FOREIGN KEY (producto_id, comercio_id)
        REFERENCES producto (id, comercio_id) ON DELETE CASCADE
);
CREATE INDEX ix_imagen_producto ON imagen_producto (producto_id);

-- Variantes de un producto (por ejemplo talle y color en el rubro ropa).
CREATE TABLE variante (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT      NOT NULL REFERENCES comercio (id) ON DELETE CASCADE,
    producto_id BIGINT      NOT NULL,
    talle       VARCHAR(20),
    color       VARCHAR(30),
    disponible  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_variante_producto FOREIGN KEY (producto_id, comercio_id)
        REFERENCES producto (id, comercio_id) ON DELETE CASCADE,
    CONSTRAINT ck_variante_atributos CHECK (talle IS NOT NULL OR color IS NOT NULL)
);
CREATE INDEX ix_variante_producto ON variante (producto_id);
